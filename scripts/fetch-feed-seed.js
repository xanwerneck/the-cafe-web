const fs = require("fs");
const https = require("https");
const path = require("path");

const API_URL =
  process.env.FEED_SEED_API_URL ||
  "https://the-cafe-api-service-ffm7qsxejq-rj.a.run.app/api/coffees?page=0";
const PAGE_SIZE = 4;
const OUTPUT_PATH = path.join(__dirname, "../lib/coffees/feedSeed.js");

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (response) => {
        let body = "";

        response.on("data", (chunk) => {
          body += chunk;
        });

        response.on("end", () => {
          if (response.statusCode < 200 || response.statusCode >= 300) {
            reject(
              new Error(`API request failed: ${response.statusCode} ${response.statusMessage}`),
            );
            return;
          }

          try {
            resolve(JSON.parse(body));
          } catch (error) {
            reject(new Error(`Failed to parse API response: ${error.message}`));
          }
        });
      })
      .on("error", reject);
  });
}

async function main() {
  const data = await fetchJson(API_URL);

  if (!Array.isArray(data)) {
    throw new Error("Expected API response to be an array");
  }

  const coffees = data.slice(0, PAGE_SIZE);

  if (coffees.length === 0) {
    throw new Error("API returned no coffees");
  }

  const content = `// Generated by scripts/fetch-feed-seed.js — do not edit manually
// Last updated: ${new Date().toISOString()}
// Run: npm run fetch-feed-seed

export const feedSeedCoffees = ${JSON.stringify(coffees, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, content, "utf8");

  console.log(`Wrote ${coffees.length} coffees to ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
